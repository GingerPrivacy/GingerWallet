#!/usr/bin/env bash
set -euo pipefail

find_repo_root() {
  local d="$PWD"
  while [[ "$d" != "/" ]]; do
    [[ -f "$d/flake.nix" ]] && { echo "$d"; return 0; }
    d="$(dirname "$d")"
  done
  echo "ERROR: Could not find flake.nix in any parent directory." >&2
  exit 1
}

nix_build_flags=(
  --extra-experimental-features nix-command
  --extra-experimental-features flakes
)

update_deps() {
  local attr="$1"        # .#packages.x86_64-linux.default
  local target="$2"      # deps.nix

  echo "==> Updating ${target} from ${attr}.passthru.fetch-deps"

  local helper
  helper="$(nix build "${attr}.passthru.fetch-deps" \
            --no-link --print-out-paths \
            "${nix_build_flags[@]}")"

  if [[ -z "$helper" || ! -e "$helper" ]]; then
    echo "ERROR: nix did not return a valid output path for fetch-deps." >&2
    exit 2
  fi

  # Current Nixpkgs fetch-deps helpers produce JSON. Keep the .nix format used
  # by flake.nix, and only replace the existing manifest after conversion.
  local temp_dir
  temp_dir="$(mktemp -d)"
  trap 'rm -rf "$temp_dir"' EXIT

  "$helper" "$temp_dir/deps.json"
  NUGET_DEPS_JSON="$temp_dir/deps.json" nix eval \
    "${nix_build_flags[@]}" --impure --raw --expr '
      let
        packages = builtins.fromJSON (builtins.readFile (builtins.getEnv "NUGET_DEPS_JSON"));
        nixString = value: builtins.replaceStrings [ "\${" ] [ "\\\${" ] (builtins.toJSON value);
        packageLine = package:
          assert builtins.all (name: builtins.elem name [ "pname" "version" "hash" "url" ]) (builtins.attrNames package);
          "  (fetchNuGet { pname = ${nixString package.pname}; "
          + "version = ${nixString package.version}; "
          + "hash = ${nixString package.hash};"
          + (if package ? url then " url = ${nixString package.url};" else "")
          + " })\n";
      in
        "# Generated by Contrib/update-nuget-deps.sh.\n"
        + "# Package identities and hashes from the Nix fetch-deps helper.\n\n"
        + "{ fetchNuGet }: [\n"
        + builtins.concatStringsSep "" (map packageLine packages)
        + "]\n"
    ' > "$temp_dir/deps.nix"

  nix-instantiate --parse "$temp_dir/deps.nix" > /dev/null
  mv "$temp_dir/deps.nix" "$target"
  rm -rf "$temp_dir"
  trap - EXIT
  echo "    Wrote $target"
}

main() {
  local root
  root="$(find_repo_root)"
  cd "$root"

  update_deps ".#packages.x86_64-linux.default" "deps.nix"

  update_deps ".#packages.x86_64-linux.all" "deps-all.nix"

  echo "==> Done. Commit deps.nix and deps-all.nix"
}

main "$@"
